from prometheus_client import (
    CONTENT_TYPE_LATEST,
    CollectorRegistry,
    Counter,
    Gauge,
    generate_latest,
)

# Use a dedicated registry to avoid conflicts during testing or hot-reloading
registry = CollectorRegistry(auto_describe=True)

# Application Health Metrics
APP_STATUS = Gauge(
    "resiliops_application_status",
    "Current status of registered application (1 = UP/Healthy, 0 = DOWN)",
    ["app_name", "app_id", "url"],
    registry=registry,
)

HEALTHCHECK_FAILURES_TOTAL = Counter(
    "resiliops_healthcheck_failures_total",
    "Total number of HTTP health-check failures per application",
    ["app_name"],
    registry=registry,
)

APP_RESPONSE_TIME_SECONDS = Gauge(
    "resiliops_application_response_time_seconds",
    "Application HTTP response latency in seconds",
    ["app_name"],
    registry=registry,
)

# System Resource Metrics (psutil)
SYSTEM_CPU_PERCENT = Gauge(
    "resiliops_system_cpu_usage_percent",
    "Overall host CPU utilization percentage",
    ["type"],
    registry=registry,
)

SYSTEM_MEMORY_PERCENT = Gauge(
    "resiliops_system_memory_usage_percent",
    "Overall host RAM memory utilization percentage",
    ["type"],
    registry=registry,
)

SYSTEM_MEMORY_AVAILABLE_BYTES = Gauge(
    "resiliops_system_memory_available_bytes",
    "Available physical memory on host system in bytes",
    registry=registry,
)

# Incident Metrics
INCIDENTS_TOTAL = Counter(
    "resiliops_incidents_total",
    "Total incidents automatically generated by failure detection engine",
    ["severity", "type"],
    registry=registry,
)


def export_metrics() -> tuple[bytes, str]:
    """Generates the Prometheus plain-text representation of all metrics."""
    return generate_latest(registry), CONTENT_TYPE_LATEST

